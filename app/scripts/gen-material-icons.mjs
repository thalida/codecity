// Regenerate src/constants/materialIcons.ts, the name→URL map of the glyphs
// utils/fileIcons.ts can resolve to. Run from app/ after editing
// src/constants/fileIconMap.ts:  node scripts/gen-material-icons.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const src = readFileSync('src/constants/fileIconMap.ts', 'utf8');
// Match `=` as well as `:`: missing the generic-fallback consts ships a folder
// falling back to an icon with no bundled URL, which renders blank.
const scraped = [...new Set([...src.matchAll(/[:=] ?'([a-z0-9_-]+)'/g)].map((m) => m[1]))];
// Folder glyphs need their `-open` twin too, for an expanded directory.
// Material ships one for every folder-* icon plus the generic `folder`.
const withOpen = new Set(scraped);
for (const n of scraped) {
  if ((n === 'folder' || n.startsWith('folder-')) && !n.endsWith('-open')) {
    withOpen.add(`${n}-open`);
  }
}
const names = [...withOpen].sort();

const pkgDir = 'node_modules/material-icon-theme/icons';
const missing = names.filter((n) => !existsSync(`${pkgDir}/${n}.svg`));
if (missing.length) {
  console.error('Icons not present in material-icon-theme:', missing);
  process.exit(1);
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const imports = names
  .map((n) => `import ${camel(n)} from 'material-icon-theme/icons/${n}.svg?url';`)
  .join('\n');
// Shorthand where the basename is already the import var, quoted otherwise.
// Keeps the output eslint-clean, so re-running the generator is idempotent.
const entries = names
  .map((n) => (/^[a-z][a-zA-Z0-9_]*$/.test(n) ? `  ${n},` : `  '${n}': ${camel(n)},`))
  .join('\n');

const out = `// constants/materialIcons.ts — GENERATED by scripts/gen-material-icons.mjs.
// Every glyph utils/fileIcons.ts can resolve to, as ?url imports so Vite
// self-hosts them and a name with no file in the package fails at BUILD.
// Regenerate after editing constants/fileIconMap.ts.

${imports}

/** Material icon basename -> served asset URL (resolved by Vite at build). */
export const MATERIAL_ICON_URLS: Record<string, string> = {
${entries}
};
`;
writeFileSync('src/constants/materialIcons.ts', out);
console.log(`Wrote src/constants/materialIcons.ts (${names.length} icons).`);
