// Regenerate src/constants/materialIcons.ts — the name→URL map of the Material
// Icon Theme glyphs that utils/fileIcons.ts can resolve to, imported as ?url
// assets from the pinned material-icon-theme package (Vite bundles each into
// the build, self-hosted, no runtime CDN). Run from app/ after editing the
// lookup maps in src/constants/fileIcons.ts:
//
//   node scripts/gen-material-icons.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const src = readFileSync('src/constants/fileIcons.ts', 'utf8');
// Icon basenames are the quoted RHS of every map entry (`: 'typescript'`) AND
// every generic-fallback const (`GENERIC_FOLDER = 'folder'`). Match both `:`
// and `=` — missing the generics ships folders that fall back to the generic
// icon with no bundled URL (blank glyph).
const names = [...new Set([...src.matchAll(/[:=] ?'([a-z0-9_-]+)'/g)].map((m) => m[1]))].sort();

const pkgDir = 'node_modules/material-icon-theme/icons';
const missing = names.filter((n) => !existsSync(`${pkgDir}/${n}.svg`));
if (missing.length) {
  console.error('Icons not present in material-icon-theme:', missing);
  process.exit(1);
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const imports = names.map((n) => `import ${camel(n)} from 'material-icon-theme/icons/${n}.svg?url';`).join('\n');
// Property shorthand when the basename is already a valid identifier equal to
// the import var (e.g. `audio`); quoted "key: var" for hyphenated names
// (e.g. `'folder-src': folderSrc`). Keeps the output eslint-clean
// (object-shorthand) so re-running the generator is idempotent.
const entries = names
  .map((n) => (/^[a-z][a-zA-Z0-9_]*$/.test(n) ? `  ${n},` : `  '${n}': ${camel(n)},`))
  .join('\n');

const out = `// constants/materialIcons.ts — GENERATED by scripts/gen-material-icons.mjs.
// Material Icon Theme file/folder glyphs the resolvers (utils/fileIcons.ts)
// can produce, imported as URL assets from the pinned material-icon-theme
// package. Vite bundles each into the build and resolves the import to its
// served URL — self-hosted (no runtime CDN), and a name with no file in the
// package fails at BUILD. The icons-exist test keeps this in sync with the
// lookup maps. Regenerate after editing constants/fileIcons.ts.

${imports}

/** Material icon basename -> served asset URL (resolved by Vite at build). */
export const MATERIAL_ICON_URLS: Record<string, string> = {
${entries}
};
`;
writeFileSync('src/constants/materialIcons.ts', out);
console.log(`Wrote src/constants/materialIcons.ts (${names.length} icons).`);
