// state/settingsReactions.ts — Settings-change → scene-rebuild / refresh wiring.
//
// Two string-valued computed signatures drive ONE effect each:
//   REBUILD_SIGNATURE → scheduleRebuild   (full applyManifest)
//   REFRESH_SIGNATURE → flagRefresh       (the 'rebuilding' status flash only)
//
// The actual material/uniform refresh for a refresh-class Save is REACTIVE:
// the controls write the settings store on Save, and each component's own
// settings effect (plus postFx's BLOOM effect) re-applies its uniforms. This
// effect's only job is the brief 'rebuilding' status flash so the user sees
// the Save register.
//
// The signatures are GENERATED entirely from each settings field's `route`
// metadata (ChangeRoute.Rebuild | Refresh | Live) via routeSignature() — no
// hand-kept per-store key lists. A field changing only flips the signature for
// its own route, so the wrong effect never fires (route: Live fields flip
// neither). Every settings store is schema-driven, so there are no legacy lists.

import { computed, effect, untracked } from '@preact/signals';

import {
  MANIFEST,
  REBUILD_STATUS,
  RebuildStatus,
  LAST_REBUILD_ERROR,
  LAST_UPDATED_AT,
} from '@/state/stores/manifest';
import { routeSignature, ChangeRoute } from '@/state/settingsSchema';
import { isEmptyManifest } from '@/utils/manifest';
import type { Manifest } from '@/types';

// Min-dwell for the 'rebuilding' indicator on the material-only path.
const HOT_REBUILD_MIN_DWELL_MS = 220;

interface CommitReactionsOpts {
  applyManifest(m: unknown): Promise<void>;
  invalidateLayoutCache(): void;
}

// ── Change signatures (auto-generated by route) ────────────────────────────
// Each is a STRING that changes iff a key with the matching route changes, so
// the effect fires only for that route — no cross-firing. routeSignature()
// compiles every schema-driven (settingSignal) field with that route.
//   REBUILD_SIGNATURE  → scheduleRebuild   (full applyManifest)
//   REFRESH_SIGNATURE  → flagRefresh       (status flash; refresh is reactive)
// (route: Live fields are in neither — read per-frame / driven elsewhere.)
const REBUILD_SIGNATURE = computed(() => routeSignature(ChangeRoute.Rebuild));
const REFRESH_SIGNATURE = computed(() => routeSignature(ChangeRoute.Refresh));

export function attachCommitReactions({
  applyManifest,
  invalidateLayoutCache,
}: CommitReactionsOpts): () => void {
  // Effects fire synchronously on first call. Suppress reactions until all
  // subscriptions are wired so the initial fire doesn't trigger a rebuild.
  let armed = false;

  let hotIdleTimer: ReturnType<typeof setTimeout> | 0 = 0;

  async function scheduleRebuild() {
    if (!armed) return;
    REBUILD_STATUS.value = RebuildStatus.Rebuilding;
    try {
      // Config changes that hit this path always invalidate the layout cache:
      // the manifest didn't change but a layout-affecting config value did,
      // so reuseLayoutFrom would skip the recompute and the change would
      // have no visible effect. Live-update polls never trigger scheduleRebuild
      // so they keep using the cache.
      invalidateLayoutCache();
      // Re-apply the current MANIFEST (the fetch layer's source of truth) with
      // the new settings + invalidated layout cache. peek() — NOT .value — so
      // the rebuild effect tracks ONLY REBUILD_SIGNATURE; a tracked read would
      // subscribe it to MANIFEST and double-apply alongside useCityScene's
      // render effect on every manifest change.
      const manifest = MANIFEST.peek();
      if (!isEmptyManifest(manifest)) {
        await applyManifest(manifest as Manifest);
      }
      REBUILD_STATUS.value = RebuildStatus.Idle;
      LAST_REBUILD_ERROR.value = null;
    } catch (err) {
      REBUILD_STATUS.value = RebuildStatus.Error;
      LAST_REBUILD_ERROR.value = err instanceof Error ? err.message : String(err);
    }
  }

  // The refresh itself is reactive (component + postFx effects re-apply uniforms
  // when their settings stores change on Save). This only drives the brief
  // 'rebuilding' status flash so the user sees the Save register.
  function flagRefresh() {
    if (!armed) return;
    if (hotIdleTimer) clearTimeout(hotIdleTimer);
    REBUILD_STATUS.value = RebuildStatus.Rebuilding;
    // Hold the 'rebuilding' indicator for a min-dwell so the user sees the
    // yellow flash. Only transition if no rebuild is also in flight —
    // applyManifest owns the final state then.
    hotIdleTimer = setTimeout(() => {
      hotIdleTimer = 0;
      if (REBUILD_STATUS.value === RebuildStatus.Rebuilding) {
        REBUILD_STATUS.value = RebuildStatus.Idle;
        LAST_REBUILD_ERROR.value = null;
        LAST_UPDATED_AT.value = Date.now();
      }
    }, HOT_REBUILD_MIN_DWELL_MS);
  }

  // Each effect must track ONLY its signature computed, so the imperative work
  // (which writes REBUILD_STATUS) runs untracked() — otherwise the effect would
  // subscribe to whatever those signals read and re-fire spuriously.
  const unsubRebuild = effect(() => {
    void REBUILD_SIGNATURE.value; // establish tracking
    if (!armed) return;
    untracked(() => {
      void scheduleRebuild();
    });
  });

  const unsubRefresh = effect(() => {
    void REFRESH_SIGNATURE.value; // establish tracking
    if (!armed) return;
    untracked(() => flagRefresh());
  });

  armed = true;

  return function dispose() {
    armed = false;
    if (hotIdleTimer) {
      clearTimeout(hotIdleTimer);
      hotIdleTimer = 0;
    }
    unsubRebuild();
    unsubRefresh();
  };
}
